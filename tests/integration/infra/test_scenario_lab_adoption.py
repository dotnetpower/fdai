LB_IP = "203.0.113.10"


def _workload(kind: str, name: str, replicas: int, ready: int | None = None) -> dict:
    ready = replicas if ready is None else ready
    return {
        "kind": kind,
        "metadata": {"name": name, "generation": 2},
        "spec": {"replicas": replicas},
        "status": {
            "observedGeneration": 2,
            "readyReplicas": ready,
            "availableReplicas": ready,
            "updatedReplicas": replicas,
        },
    }


def _kube(**overrides: Any) -> dict:
    pinned = sorted(READBACK["pinned_images"]())
    workloads = [
        _workload(kind, name, replicas)
        for (kind, name), replicas in READBACK["EXPECTED_WORKLOADS"].items()
    ]
    services = [
        {
            "kind": "Service",
            "metadata": {
                "name": "store-front",
                "annotations": {
                    "service.beta.kubernetes.io/azure-dns-label-name": HOST.split(".")[0]
                },
            },
            "spec": {"type": "LoadBalancer"},
            "status": {"loadBalancer": {"ingress": [{"ip": LB_IP}]}},
        },
        {"kind": "Service", "metadata": {"name": "store-admin"}, "spec": {"type": "ClusterIP"}},
    ]
    pods = [
        {
            "kind": "Pod",
            "metadata": {"name": f"pod-{index}", "labels": {"app": f"app-{index}"}},
            "spec": {"containers": [{"name": "main", "image": image}]},
            "status": {
                "phase": "Running",
                "containerStatuses": [{"name": "main", "imageID": f"docker.io/x{image[-72:]}"}],
            },
        }
        for index, image in enumerate(overrides.pop("images", pinned))
    ]
    items = workloads + services + pods + overrides.pop("extra", [])
    return {"kind": "List", "items": items}


def _evaluate(kube: dict | None = None, **overrides: Any) -> list[str]:
    arguments = {
        "kube": kube or _kube(),
        "public_ips": [{"ipAddress": LB_IP, "fqdn": HOST}],
        "dns_addresses": [LB_IP],
        "http_status": 200,
        "hostname": HOST,
        "dns_label": HOST.split(".")[0],
        "pinned": READBACK["pinned_images"](),
    }
    arguments.update(overrides)
    _, failures = READBACK["evaluate"](**arguments)
    return failures


def test_store_demo_readback_verifies_every_required_observation() -> None:
    assert _evaluate() == []

    kube = _kube()
    kube["items"][2]["status"]["readyReplicas"] = 2
    assert "workload_not_ready:Deployment/order-service" in _evaluate(kube)
    exposed = _kube()
    exposed["items"][10]["spec"]["type"] = "LoadBalancer"
    assert "store_admin_not_private" in _evaluate(exposed)
    assert "unexpected_exposed_service:store-admin" in _evaluate(exposed)
    tagged = _kube(images=["ghcr.io/azure-samples/aks-store-demo/order-service:2.2.0"])
    assert "unpinned_image:app-0/main" in _evaluate(tagged)
    extra = _kube(extra=[_workload("Deployment", "api-backend", 1)])
    assert "unexpected_workload:Deployment/api-backend" in _evaluate(extra)
    assert "dns_does_not_resolve_to_load_balancer" in _evaluate(dns_addresses=["198.51.100.7"])
    assert "azure_public_ip_mismatch" in _evaluate(public_ips=[])
    assert "store_front_health_failed" in _evaluate(http_status=503)


