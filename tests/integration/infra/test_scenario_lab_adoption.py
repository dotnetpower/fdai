class FakeAz:
    def __init__(self, resources: list[dict], assignments: list[dict], nsg_id: str | None):
        self.resources = resources
        self.assignments = assignments
        self.nsg_id = nsg_id
        self.calls: list[tuple[str, ...]] = []

    def __call__(self, arguments: Sequence[str]) -> Any:
        self.calls.append(tuple(arguments[:3]))
        if arguments[:2] == ["resource", "list"]:
            return self.resources
        if arguments[:3] == ["role", "assignment", "list"]:
            return self.assignments
        if arguments[:3] == ["network", "nic", "show"]:
            return {"networkSecurityGroup": {"id": self.nsg_id} if self.nsg_id else None}
        raise AssertionError(arguments)


