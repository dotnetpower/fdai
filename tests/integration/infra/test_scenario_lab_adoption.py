FAKE_AZ = """#!/usr/bin/env bash
set -euo pipefail
printf '%s\n' "$*" >>"$FAKE_AZ_LOG"
if [[ "$*" == *"aks stop"* ]]; then
  printf 'Stopped' >"$FAKE_AZ_POWER"
  exit 0
fi
if [[ "$*" == *"[[provisioningState, powerState.code]]"* ]]; then
  row="$(head -n 1 "$FAKE_AZ_ROWS")"
  tail -n +2 "$FAKE_AZ_ROWS" >"$FAKE_AZ_ROWS.next" && mv "$FAKE_AZ_ROWS.next" "$FAKE_AZ_ROWS"
  [[ "$row" == "fail" ]] && exit 1
  printf '%b\n' "$row"
  exit 0
fi
if [[ "$*" == *"--query powerState.code"* ]]; then
  cat "$FAKE_AZ_POWER"
  exit 0
fi
exit 2
"""


def _run_restore(tmp_path: Path, rows: list[str]) -> tuple[int, list[str]]:
    workflow = WORKFLOW.read_text(encoding="utf-8")
    step = _step(workflow, "Restore AKS power state")
    script = "\n".join(
        line.removeprefix("          ") for line in step.split("run: |\n", 1)[1].splitlines()
    )
    bin_dir = tmp_path / "bin"
    bin_dir.mkdir()
    (bin_dir / "az").write_text(FAKE_AZ, encoding="utf-8")
    (bin_dir / "sleep").write_text("#!/usr/bin/env bash\nexit 0\n", encoding="utf-8")
    for tool in ("az", "sleep"):
        (bin_dir / tool).chmod(0o755)
    (tmp_path / "rows").write_text("\n".join(rows) + "\n", encoding="utf-8")
    (tmp_path / "power").write_text("Running", encoding="utf-8")
    (tmp_path / "sre-demo-lab-aks-started-by-run").write_text("", encoding="utf-8")
    environment = {
        "PATH": f"{bin_dir}:{os.environ.get('PATH', '')}",
        "RUNNER_TEMP": str(tmp_path),
        "SCENARIO_LAB_RESOURCE_GROUP_NAME": RG,
        "FAKE_AZ_LOG": str(tmp_path / "az.log"),
        "FAKE_AZ_ROWS": str(tmp_path / "rows"),
        "FAKE_AZ_POWER": str(tmp_path / "power"),
    }
    result = subprocess.run(  # noqa: S603 - resolved Bash and an extracted repository step.
        [str(BASH), "-c", script],
        capture_output=True,
        check=False,
        env=environment,
        text=True,
        timeout=60,
    )
    log = (tmp_path / "az.log").read_text(encoding="utf-8").splitlines()
    return result.returncode, log


@pytest.mark.parametrize(
    ("rows", "stops"),
    [
        (["Succeeded\\tStopped"], 0),
        (["Updating\\tRunning", "Succeeded\\tRunning"], 1),
        (["fail", "Succeeded\\tRunning"], 1),
        (["Failed\\tRunning"], 1),
    ],
)
def test_restore_settles_a_running_operation_before_one_bounded_stop(
    tmp_path: Path, rows: list[str], stops: int
) -> None:
    returncode, log = _run_restore(tmp_path, rows)

    assert returncode == 0
    assert sum("aks stop" in line for line in log) == stops


FAKE_START_AZ = """#!/usr/bin/env bash
set -euo pipefail
printf '%s\n' "$*" >>"$FAKE_AZ_LOG"
next_result() {
  local results="$1"
  local result
  result="$(head -n 1 "$results")"
  tail -n +2 "$results" >"$results.next" && mv "$results.next" "$results"
  case "$result" in
    auth)
      printf "ERROR: (AuthorizationFailed) The client 'leak-client' with object id "
      printf "'leak-object' does not have authorization over scope '/subscriptions/leak'.\n"
      printf 'Code: AuthorizationFailed\n'
      exit 1
      ;;
    other)
      printf "ERROR: (OperationNotAllowed) leak-message for '/subscriptions/leak'.\n"
      printf 'Code: OperationNotAllowed\n'
      exit 1
      ;;
  esac
}
if [[ "$*" == "resource list"* ]]; then
  printf '1\n'
  exit 0
fi
if [[ "$*" == "aks start"* ]]; then
  next_result "$FAKE_AZ_AKS_RESULTS"
  printf 'Running' >"$FAKE_AZ_POWER"
  exit 0
fi
if [[ "$*" == "aks show"* ]]; then
  cat "$FAKE_AZ_POWER"
  printf '\n'
  exit 0
fi
if [[ "$*" == "mysql flexible-server start"* ]]; then
  next_result "$FAKE_AZ_MYSQL_RESULTS"
  printf 'Ready' >"$FAKE_AZ_MYSQL"
  exit 0
fi
if [[ "$*" == "mysql flexible-server show"* ]]; then
  cat "$FAKE_AZ_MYSQL"
  printf '\n'
  exit 0
fi
exit 2
"""


