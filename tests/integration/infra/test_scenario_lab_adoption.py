def test_store_demo_readback_cli_retains_a_repository_safe_document(tmp_path: Path) -> None:
    output = tmp_path / "readback.json"
    responses = {"kubectl": _kube(), "aks": "MC_rg-lab-example_aks-store-demo_koreacentral"}

    def run(command: Sequence[str]) -> Any:
        if command[0] == "kubectl":
            return responses["kubectl"]
        if command[1] == "aks":
            return responses["aks"]
        return [{"ipAddress": LB_IP, "fqdn": HOST}]

    arguments = [
        "--output",
        str(output),
        "--store-front-url",
        f"http://{HOST}",
        "--resource-group",
        RG,
        "--cluster-name",
        "aks-store-demo",
        "--source-commit",
        "a" * 40,
        "--run-id",
        "123",
        "--run-attempt",
        "1",
    ]

    status = READBACK["main"](
        arguments,
        run=run,
        resolver=lambda _: [LB_IP],
        prober=lambda _: 200,
        sleep=lambda _: None,
    )

    document = json.loads(output.read_text(encoding="utf-8"))
