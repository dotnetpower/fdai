def _plan_change(address: str, before_scope: str, after_scope: str, **overrides: Any) -> dict:
    change = {
        "actions": ["delete", "create"],
        "replace_paths": [["scope"]],
        "importing": {"id": "retained"},
        "before": {
            "scope": before_scope,
            "principal_id": RUNNER,
            "role_definition_name": USER_ROLE,
        },
        "after": {"scope": after_scope, "principal_id": RUNNER, "role_definition_name": USER_ROLE},
    }
    change.update(overrides)
    return {"address": address, "change": change}


