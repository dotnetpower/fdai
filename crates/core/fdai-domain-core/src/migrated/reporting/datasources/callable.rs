#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct CallableDataSource {
    pub initialized: bool,
}

impl CallableDataSource {
    #[allow(clippy::all, unused_variables, unused_mut, unused_parens, unused_assignments, unreachable_code)]
    #[must_use]
    pub fn name(&self) -> String {
        if !self.initialized {
            return String::new();
        }
        String::new()
    }
    #[allow(clippy::all, unused_variables, unused_mut, unused_parens, unused_assignments, unreachable_code)]
    pub async fn query(&self, mut spec: String, mut since: String, mut until: String, mut variables: std::collections::BTreeMap<String, String>) -> Result<String, &'static str> {
        if !self.initialized {
            return Err("component_not_initialized");
        }
        Err("runtime_binding_required")
    }
}

pub const PUBLIC_EXPORTS: &[&str] = &["CallableDataSource", "CallableQueryFn"];
