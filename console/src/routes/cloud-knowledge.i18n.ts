/** Resolve this bounded panel's English/Korean copy with the Console locale and English fallback. */
export function cloudKnowledgeText(
  key: CloudKnowledgeMessageKey,
  params?: Readonly<Record<string, string | number>>,
): string {
  const template = (getLocale() === "ko" ? ko[key] : undefined) || en[key];
  if (params === undefined) return template;
  return template.replace(/\{(\w+)\}/g, (whole, name: string) =>
    name in params ? String(params[name]) : whole,
  );
}
