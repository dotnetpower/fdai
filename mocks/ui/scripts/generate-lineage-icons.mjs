import { readFile, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const packageRoot = resolve(process.argv[2] || ".fdai/lineage-icon-build/node_modules/lucide");
const metadata = JSON.parse(await readFile(resolve(packageRoot, "package.json"), "utf8"));
if (metadata.version !== "0.547.0") throw new Error("Lineage icons require lucide@0.547.0");
const icons = createRequire(import.meta.url)(resolve(packageRoot, "dist/cjs/lucide.js"));
const names = ["Search", "RotateCcw", "Maximize", "Minimize", "ZoomIn", "ZoomOut", "LocateFixed", "Database", "Server", "Boxes", "Box", "Activity", "BookOpen", "ShieldCheck", "GitBranch", "Network", "FileText", "Layers", "CircleHelp", "Check", "Clock", "TriangleAlert", "X", "ArrowLeft", "ArrowRight", "ArrowUp", "ArrowDown", "PanelRightClose", "PanelRightOpen", "Scan", "ChevronDown", "ChevronRight", "ListFilter", "Map", "Copy", "ExternalLink"];
const subset = Object.fromEntries(names.map(name => {
  if (!Array.isArray(icons[name])) throw new Error(`Missing icon ${name}`);
  return [name, icons[name]];
}));
const license = await readFile(resolve(packageRoot, "LICENSE"), "utf8");
const output = resolve(dirname(fileURLToPath(import.meta.url)), "../assets/lineage-icons.js");
await writeFile(output, `/* Generated by mocks/ui/scripts/generate-lineage-icons.mjs from lucide@0.547.0.\n${license}*/\nwindow.fdaiLineageIcons = ${JSON.stringify(subset)};\n`);
console.log(`Generated ${names.length} local Lucide icons`);
