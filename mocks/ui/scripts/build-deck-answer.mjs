import { readFile, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "../../..");
const require = createRequire(join(root, "console/package.json"));
const { build } = require("esbuild");
const destination = join(root, "mocks/ui/assets/deck-answer.js");
const result = await build({
  entryPoints: [join(root, "mocks/ui/assets/deck-answer.ts")],
  bundle: true,
  format: "iife",
  platform: "browser",
  target: "es2022",
  charset: "utf8",
  minify: true,
  write: false,
  banner: { js: "// Generated by node mocks/ui/scripts/build-deck-answer.mjs. Do not edit." },
});
const content = result.outputFiles[0].text;
if (process.argv.includes("--check")) {
  if (await readFile(destination, "utf8") !== content) {
    throw new Error("Common answer bundle is stale. Run node mocks/ui/scripts/build-deck-answer.mjs.");
  }
} else {
  await writeFile(destination, content);
}
